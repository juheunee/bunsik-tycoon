package bunsik.common;

/**
 * 서버와 클라이언트가 주고받는 메시지의 종류(= 주문서 양식 목록).
 *
 * <p>한 줄 메시지는 {@code 종류|값1|값2|...} 모양이며, 각 종류 옆 주석에 값의 순서를 적었다.
 * 이 목록은 두 사람 작업의 "계약서"이므로 바꿀 때는 반드시 팀원과 합의하고 양쪽 코드를 함께 고친다.
 */
public enum MessageType {

    // ===================== 클라이언트 → 서버 =====================

    /** 접속 인사. 닉네임|모드(SOLO 또는 VERSUS) */
    HELLO,
    /** 대기실 준비 버튼. true/false */
    READY,
    /** 내 캐릭터 위치 알림(초당 최대 10번). x|y|왼쪽을보는지(true/false) */
    MOVE,
    /** 스페이스 키: 가까운 테이블·부엌과 상호작용. x|y */
    INTERACT,
    /** 접시에 메뉴를 끌어다 놓음 = 요리 시작. 메뉴코드(예: TTEOKBOKKI) */
    COOK,
    /** 정상 종료 인사(값 없음) */
    LEAVE,

    // ===================== 서버 → 클라이언트 =====================

    /** 접속 확인. 내 접속번호 */
    WELCOME,
    /** 입장 거절(대기실 가득 참 등). 이유 */
    REJECT,
    /** 대기실 현황. 접속번호:닉네임:준비(true/false) 가 사람 수만큼 이어짐 */
    LOBBY,
    /** 게임 화면으로 전환. 내슬롯|인원수|0번닉네임|1번닉네임(1P면 -) */
    START,
    /** 시작 카운트다운. 남은초(3,2,1), 0이면 게임 시작 */
    COUNTDOWN,
    /** 식당 하나의 현재 상태 전체(0.1초마다). 형식은 {@link StoreSnapshot} 참고 */
    STATE,
    /** 부엌 화면 열기(서버가 부엌 근처임을 확인함) */
    OPEN_KITCHEN,
    /** 요리 완료. 메뉴코드 */
    COOK_DONE,
    /** 화면 위쪽에 잠깐 띄울 안내 문구. 문구 */
    TOAST,
    /** 게임 종료와 결과. 승자슬롯(-1 무승부, -2 혼자하기)|인원수|닉네임:만족도:판매:골드:손님 ... */
    GAME_OVER
}
